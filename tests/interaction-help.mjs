import { mockFirebase } from './mock-firebase.mjs';
import { createRequire } from 'node:module';
import { readFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
let playwright;
try { playwright = await import('playwright'); }
catch { playwright = createRequire(resolve(process.env.CODEX_NODE_MODULES || 'C:/Users/LENOVO/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json'))('playwright'); }
const browser = await playwright.chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width:393, height:851 }, isMobile:true, hasTouch:true });
const page = await context.newPage();
await mockFirebase(page);
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.route('https://game.test/**', async route => {
  const f = new URL(route.request().url()).pathname.slice(1) || 'index.html';
  await route.fulfill({ contentType:f.endsWith('.js')?'application/javascript':f.endsWith('.css')?'text/css':'text/html', body:await readFile(resolve(root,'app/src/main/assets',f)) });
});
const ready = () => page.waitForSelector('body[data-ready="true"]');
const saved = () => page.evaluate(async () => { const { Storage } = await import('./storage.js'); const s = await new Storage().open(); const g = await s.loadGame(); s.db.close(); return g; });
const openNew = async () => { await page.locator('#start-button').click(); await page.getByRole('button',{name:'Play',exact:true}).click(); await page.waitForTimeout(100); };
const close = () => page.locator('#modal button[value="cancel"]').click();
try {
  await mkdir(resolve(root,'build/previews'),{recursive:true});
  await page.goto('https://game.test/'); await ready();
  assert.equal(await page.locator('#resume-button').isVisible(),true);
  assert.equal(await page.locator('#resume-button').isDisabled(),true);
  assert.equal(await page.locator('#start-button').textContent(),'NEW GAME');
  const menu = await page.locator('.home-menu').boundingBox();
  await page.locator('[data-action="help"]').click();
  assert.match(await page.locator('#modal-body').textContent(),/score 4 points lower/);
  await close(); await openNew();
  await page.locator('[data-spawn="4"]').tap();
  assert.equal(await page.locator('#modal-title').textContent(),'Switch to spawning 4?');
  assert.equal((await saved()).nextTile,2);
  assert.equal((await saved()).fourWarningShown,true);
  await page.screenshot({path:resolve(root,'build/previews/spawn-4-warning.png')});
  await page.getByRole('button',{name:'Keep 2',exact:true}).click();
  await page.locator('[data-spawn="4"]').tap();
  assert.equal(await page.locator('#modal').evaluate(e=>e.open),false);
  assert.equal((await saved()).nextTile,4);
  await page.locator('[data-spawn="2"]').tap();
  await page.reload(); await ready(); await page.locator('#resume-button').click();
  await page.locator('[data-spawn="4"]').tap();
  assert.equal(await page.locator('#modal').evaluate(e=>e.open),false,'warning stays dismissed after reload');
  assert.equal((await saved()).nextTile,4);
  // A hold explains assistance without toggling it; a short tap still toggles.
  const touch = await context.newCDPSession(page);
  const box = await page.locator('#assistance-button').boundingBox();
  const point = {x:box.x+box.width/2,y:box.y+box.height/2};
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point]});
  await page.waitForTimeout(650);
  assert.equal(await page.locator('#modal-title').textContent(),'Assistance');
  await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.equal((await saved()).assisted,false);
  assert.match(await page.locator('#modal-body').textContent(),/Smart spawning/);
  assert.match(await page.locator('#modal-body').textContent(),/Large-tile warning/);
  assert.match(await page.locator('#modal-body').textContent(),/Corner warning/);
  assert.match(await page.locator('#modal-body').textContent(),/highest corner tile/);
  assert.match(await page.locator('#modal-body').textContent(),/third has three tiles/);
  assert.match(await page.locator('#modal-body').textContent(),/3 × 3: 1,024/);
  assert.match(await page.locator('#modal-body').textContent(),/8 × 8: 32,768/);
  await page.screenshot({path:resolve(root,'build/previews/assistance-help.png')});
  await close(); await page.locator('#assistance-button').tap();
  assert.equal((await saved()).assisted,true);
  await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point]});
  await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:point.x+25,y:point.y}]});
  await page.waitForTimeout(600); await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.equal(await page.locator('#modal').evaluate(e=>e.open),false,'moving away cancels the hold');
  assert.equal((await saved()).assisted,true);
  await page.locator('#assistance-button').focus(); await page.keyboard.press('Shift+F10');
  assert.equal(await page.locator('#modal-title').textContent(),'Assistance'); await close();
  await page.locator('.game-toolbar [data-action="home"]').click();
  const withSave = await page.locator('.home-menu').boundingBox();
  assert.deepEqual(withSave,menu,'home layout does not shift when a save appears');
  await page.locator('[data-action="larger"]').click();
  assert.equal(await page.locator('#resume-button').isDisabled(),true);
  assert.deepEqual(await page.locator('.home-menu').boundingBox(),menu);
  await page.screenshot({path:resolve(root,'build/previews/home-empty-slot.png')});
  await openNew(); await page.locator('[data-spawn="4"]').tap();
  assert.equal(await page.locator('#modal-title').textContent(),'Switch to spawning 4?','another size has its own warning');
  await page.getByRole('button',{name:'Use 4',exact:true}).click();
  assert.equal((await saved()).nextTile,4);
  await page.locator('[data-action="restart"]').click(); // No moves: starts immediately.
  await page.locator('[data-spawn="2"]').tap(); await page.locator('[data-spawn="4"]').tap();
  assert.equal(await page.locator('#modal-title').textContent(),'Switch to spawning 4?','restart resets the warning');
  await close();
  await page.locator('.game-toolbar [data-action="home"]').click();
  await page.locator('[data-action="leaderboard"]').click();
  assert.equal(await page.locator('#connect-button').isVisible(),false);
  assert.equal(await page.locator('.connection-link').isVisible(),false);
  await page.locator('[data-action="nickname"]').click(); await page.locator('#nickname-input').fill('Player');
  await page.getByRole('button',{name:'Save nickname',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#nickname-button').textContent.includes('Player'));
  assert.equal(await page.locator('#rankings li').count(),0);
  assert.deepEqual(errors,[]);
  console.log('Passed: stable Home layout, per-game 4 warning and persistence, assistance hold/tap/cancel, keyboard help, built-in Firebase nickname flow.');
} finally { await browser.close(); }
